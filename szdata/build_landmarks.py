#!/usr/bin/env python3
"""Curated OSM building rings -> runtime footprints. Requires shapely; no network.

Use an oriented minimum rectangle, not PCA of sampled vertices: vertex density
must not change the position or heading. Local u/v use east/south axes, in metres.
"""
import json, math
from pathlib import Path
from shapely.geometry import Polygon
from shapely.ops import unary_union
from shapely.affinity import rotate
HERE = Path(__file__).resolve().parent
SOURCE = json.loads((HERE / 'landmarks_osm.json').read_text())
LON0, LAT0, KX, KY, CELL = 113.744, 22.722, 409.6, 443.0, 250
out = {}
for lid, rows in SOURCE['landmarks'].items():
    polys = [Polygon([((lon-LON0)*KX*CELL, (LAT0-lat)*KY*CELL) for lon,lat in r['ring']]) for r in rows]
    if any(not p.is_valid for p in polys): raise ValueError('Invalid building: '+lid)
    envelope = unary_union(polys).minimum_rotated_rectangle
    corners = list(envelope.exterior.coords)[:4]
    a,b = max(zip(corners, corners[1:]+corners[:1]),key=lambda ab: math.dist(*ab))
    angle = (math.degrees(math.atan2(b[1]-a[1],b[0]-a[0]))+90)%180-90
    cx,cy = envelope.centroid.coords[0]
    local = [rotate(p,-angle,origin=(cx,cy)) for p in polys]
    bounds = unary_union(local).bounds
    parts=[]
    for row,p in zip(rows,local):
        p=p.simplify(1.5,preserve_topology=True)
        parts.append({'p':[[round(x-cx,2),round(y-cy,2)] for x,y in list(p.exterior.coords)[:-1]],'h':row['height'],'year':row['year']})
    out[lid]={'x':round(cx/CELL,5),'y':round(cy/CELL,5),'w':round(bounds[2]-bounds[0],2),'d':round(bounds[3]-bounds[1],2),'rot':round(angle,5),'parts':parts,'h':max(r['height'] for r in rows)}
    print(lid, f"{out[lid]['w']} x {out[lid]['d']} m, {angle:.1f} degrees")
text="'use strict';\n// Generated by szdata/build_landmarks.py. OSM contributors, ODbL 1.0.\nwindow.CM.SZ_LANDMARKS = "+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n'
(HERE.parent/'js'/'landmarks_sz.js').write_text(text)
